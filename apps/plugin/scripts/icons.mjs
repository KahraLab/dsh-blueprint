/**
 * Generate the Iconify subset this plugin draws with.
 *
 * The plugin ships no icon font and calls no icon API: the names in
 * `icons.json` are expanded from `@iconify-json/ph` at build time into a small
 * module. Adding a glyph is one line in the manifest and a rebuild.
 */
import fs from 'node:fs';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { getIconData } from '@iconify/utils';

const here = new URL('.', import.meta.url);
const set = JSON.parse(await readFile(new URL('../node_modules/@iconify-json/ph/icons.json', import.meta.url), 'utf8'));
const names = JSON.parse(await readFile(new URL('./icons.json', import.meta.url), 'utf8'));
const target = fileURLToPath(new URL('../src/client/ui/iconBodies.ts', here));

const bodies = {};
for (const name of names) {
  const icon = getIconData(set, name);
  if (icon === undefined) throw new Error(`icons.json: unknown phosphor icon "${name}"`);
  bodies[name] = {
    body: icon.body,
    width: icon.width ?? set.width ?? 256,
    height: icon.height ?? set.height ?? 256,
  };
}

const source = `/**
 * Generated by scripts/icons.mjs from scripts/icons.json — do not edit.
 * Run \`node scripts/icons.mjs\` after changing the manifest.
 */
export interface IconBody {
  body: string;
  width: number;
  height: number;
}

export const ICON_BODIES: Readonly<Record<string, IconBody>> = ${JSON.stringify(bodies, null, 2)};
`;
fs.writeFileSync(target, source);
console.log(`[icons] ${names.length} glyphs → src/client/ui/iconBodies.ts`);
